package com.santyramos.mirador.player

import android.net.Uri
import androidx.media3.common.C
import androidx.media3.common.MediaItem
import androidx.media3.common.MimeTypes
import androidx.media3.exoplayer.source.MediaSource
import androidx.media3.exoplayer.source.SingleSampleMediaSource
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.StreamInfo

/** Subtítulos (CC) de los videos de YouTube. */
object Subtitulos {
    private fun mimeDe(f: MediaFormat?): String? = when (f) {
        MediaFormat.VTT -> MimeTypes.TEXT_VTT
        MediaFormat.SRT -> MimeTypes.APPLICATION_SUBRIP
        MediaFormat.TTML -> MimeTypes.APPLICATION_TTML
        else -> null
    }

    /** Un subtítulo por idioma (prefiere el formato VTT); primero los hechos por personas, luego los automáticos. */
    fun deVideo(info: StreamInfo): List<Subtitulo> =
        info.subtitles.orEmpty().mapNotNull { s ->
            val mime = mimeDe(s.format) ?: return@mapNotNull null
            val tag = s.languageTag ?: return@mapNotNull null
            val nombre = (s.displayLanguageName?.takeIf { it.isNotBlank() } ?: tag).replaceFirstChar { it.uppercase() }
            Subtitulo(
                id = "$tag${if (s.isAutoGenerated) ":auto" else ""}",
                nombre = if (s.isAutoGenerated) "$nombre (automático)" else nombre,
                url = s.content, mime = mime, idioma = tag.substringBefore('-').lowercase(), auto = s.isAutoGenerated,
            ) to (s.format == MediaFormat.VTT)
        }
            .sortedByDescending { it.second } // VTT primero, para quedarnos con él al quitar repetidos
            .map { it.first }
            .distinctBy { it.id }
            .sortedWith(compareBy({ it.auto }, { it.nombre }))

    /**
     * Cuál mostrar: [elegidoEnVideo] si ya se eligió en este video ("" = desactivados); si no, el idioma que
     * dejaste la última vez ([preferencia]; vacío = ninguno), primero el hecho por personas.
     */
    fun elegir(lista: List<Subtitulo>, elegidoEnVideo: String?, preferencia: String?): Subtitulo? {
        if (elegidoEnVideo != null) return lista.firstOrNull { it.id == elegidoEnVideo }
        val idioma = preferencia?.takeIf { it.isNotBlank() } ?: return null
        return lista.firstOrNull { it.idioma == idioma && !it.auto } ?: lista.firstOrNull { it.idioma == idioma }
    }

    fun fuente(s: Subtitulo): MediaSource {
        val config = MediaItem.SubtitleConfiguration.Builder(Uri.parse(s.url))
            .setMimeType(s.mime).setLanguage(s.idioma).setLabel(s.nombre)
            .setSelectionFlags(C.SELECTION_FLAG_DEFAULT)
            .build()
        return SingleSampleMediaSource.Factory(PlayerData.fabricaGenerica()).createMediaSource(config, C.TIME_UNSET)
    }
}
